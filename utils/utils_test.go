// TestUpdateCorruptedRepo simulates a corrupted repository by removing the HEAD file, and expects Update to fail.
func TestUpdateCorruptedRepo(t *testing.T) {
    tempDir, err := ioutil.TempDir("", "gibo_test_cache")
    if err != nil {
        t.Fatalf("Failed to create tempDir: %v", err)
    }
    defer os.RemoveAll(tempDir)

    overrideCacheDir(t, tempDir)
    repoDir := utils.RepoDir()
    setupDummyRepo(t, repoDir)

    // Corrupt the repository by removing the HEAD file.
    headPath := filepath.Join(repoDir, ".git", "HEAD")
    err = os.Remove(headPath)
    if err != nil {
        t.Fatalf("Failed to remove HEAD file: %v", err)
    }

    // Call Update and expect an error due to the corrupted repository.
    _, err = utils.Update()
    if err == nil {
        t.Errorf("Expected error when updating a corrupted repo, got nil")
    }
}
