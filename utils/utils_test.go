// TestUpdate simulates updating the dummy repository and expects either "Already up to date" or "Updated".
func TestUpdate(t *testing.T) {
    tempDir, err := ioutil.TempDir("", "gibo_test_cache")
    if err != nil {
    t.Fatalf("Failed to create tempDir: %v", err)
    }
    defer os.RemoveAll(tempDir)

    overrideCacheDir(t, tempDir)
    repoDir := utils.RepoDir()
    setupDummyRepo(t, repoDir)

    // Call Update. Since we set remote pointing to itself, no changes are available.
    result, err := utils.Update()
    if err != nil {
    t.Fatalf("Update failed: %v", err)
    }

    // We expect either "Already up to date" (if pull returns an error of NoErrAlreadyUpToDate)
    // or "Updated" in case of a successful pull/reset.
    if result != "Already up to date" && result != "Updated" {
    t.Errorf("Unexpected update result: %v", result)
    }

    // To exercise the reset branch, one could simulate a pull error by tampering with the repository.
    // This test sticks to verifying the Update function completes.
}
// TestCloneIfNeededWhenRepoIsFile tests the behavior of cloneIfNeeded when the repo path exists as a file.
func TestCloneIfNeededWhenRepoIsFile(t *testing.T) {
    tempDir, err := ioutil.TempDir("", "gibo_test_cache")
    if err != nil {
        t.Fatalf("Failed to create tempDir: %v", err)
    }
    defer os.RemoveAll(tempDir)

    overrideCacheDir(t, tempDir)
    repoDir := utils.RepoDir()
    err = os.MkdirAll(filepath.Dir(repoDir), 0755)
    if err != nil {
        t.Fatalf("Failed to create parent directory for repoDir: %v", err)
    }
    // Create a file instead of a directory at repoDir.
    err = ioutil.WriteFile(repoDir, []byte("not a directory"), 0644)
    if err != nil {
        t.Fatalf("Failed to create file at repoDir: %v", err)
    }

    // Attempt to list boilerplates, which will trigger cloneIfNeeded.
    _, err = utils.ListBoilerplates()
    if err == nil {
        t.Errorf("Expected error when repoDir is not a directory, got nil")
    } else {
        if !strings.Contains(err.Error(), "is not a directory") {
            t.Errorf("Unexpected error: %v", err)
        }
    }
}

