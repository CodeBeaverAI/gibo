// setupDummyRepo initializes a fake git repository at repoDir and creates two boilerplate files.
func setupDummyRepo(t *testing.T, repoDir string) {
    // Create the repository directory
    err := os.MkdirAll(repoDir, 0755)
    if err != nil {
    t.Fatalf("Failed to create repoDir: %v", err)
    }

    // Initialize a new git repository
    repo, err := git.PlainInit(repoDir, false)
    if err != nil {
    t.Fatalf("Failed to init repo: %v", err)
    }

    // Create two dummy .gitignore files: Python.gitignore and Node.gitignore.
    boilerplates := map[string]string{
    "Python.gitignore": "python boilerplate content",
    "Node.gitignore":   "node boilerplate content",
    }
    for filename, content := range boilerplates {
    path := filepath.Join(repoDir, filename)
    err := ioutil.WriteFile(path, []byte(content), 0644)
    if err != nil {
    t.Fatalf("Failed to write file %v: %v", filename, err)
    }
    }

    // Add the files and commit so that HEAD exists.
    wt, err := repo.Worktree()
    if err != nil {
    t.Fatalf("Failed to get worktree: %v", err)
    }

    // Add all files.
    err = wt.AddGlob("*.gitignore")
    if err != nil {
    t.Fatalf("Failed to add files: %v", err)
    }

    commitHash, err := wt.Commit("initial commit", &git.CommitOptions{
    Author: &object.Signature{
    Name:  "Tester",
    Email: "tester@example.com",
    When:  time.Now(),
    },
    })
    if err != nil {
    t.Fatalf("Failed to commit: %v", err)
    }

    // Print commit hash for debugging.
    t.Logf("Dummy commit: %v", commitHash.String())

    // For Update() test: set remote "origin" to point to the repo itself
    _, err = repo.CreateRemote(&config.RemoteConfig{
    Name: "origin",
    URLs: []string{"file://" + repoDir},
    })
    if err != nil && !strings.Contains(err.Error(), "already exists") {
    t.Fatalf("Failed to create remote: %v", err)
    }
}

// overrideCacheDir sets the environment variable to force utils.RepoDir to use a temporary directory.
func overrideCacheDir(t *testing.T, tempDir string) {
    // On Unix: os.UserCacheDir checks XDG_CACHE_HOME if set.
    err := os.Setenv("XDG_CACHE_HOME", tempDir)
    if err != nil {
    t.Fatalf("Failed to set XDG_CACHE_HOME: %v", err)
    }
}

// TestListBoilerplates verifies that ListBoilerplates returns the expected boilerplates.
func TestListBoilerplates(t *testing.T) {
    // Create a temporary directory to override the user cache directory.
    tempDir, err := ioutil.TempDir("", "gibo_test_cache")
    if err != nil {
    t.Fatalf("Failed to create tempDir: %v", err)
    }
    defer os.RemoveAll(tempDir)

    overrideCacheDir(t, tempDir)
    repoDir := utils.RepoDir()
    setupDummyRepo(t, repoDir)

    boilerplates, err := utils.ListBoilerplates()
    if err != nil {
    t.Fatalf("ListBoilerplates failed: %v", err)
    }

    // Expect [Node, Python] sorted alphabetically.
    expected := []string{"Node", "Python"}
    if len(boilerplates) != len(expected) {
    t.Fatalf("Expected %d boilerplates, got %d", len(expected), len(boilerplates))
    }

    for i, name := range expected {
    if boilerplates[i] != name {
    t.Errorf("Expected boilerplate %v at index %d, got %v", name, i, boilerplates[i])
    }
    }
}

// TestPrintBoilerplate verifies that PrintBoilerplate prints the header and boilerplate content.
func TestPrintBoilerplate(t *testing.T) {
    // Create a temporary directory for the fake cache
    tempDir, err := ioutil.TempDir("", "gibo_test_cache")
    if err != nil {
    t.Fatalf("Failed to create tempDir: %v", err)
    }
    defer os.RemoveAll(tempDir)

    overrideCacheDir(t, tempDir)
    repoDir := utils.RepoDir()
    setupDummyRepo(t, repoDir)

    // Capture Stdout
    oldStdout := os.Stdout
    r, w, err := os.Pipe()
    if err != nil {
    t.Fatalf("Failed to create pipe: %v", err)
    }
    os.Stdout = w

    // Call PrintBoilerplate with lowercase name (to test case-insensitive search)
    err = utils.PrintBoilerplate("python")
    if err != nil {
    t.Fatalf("PrintBoilerplate failed: %v", err)
    }

    w.Close()
    os.Stdout = oldStdout
    var buf bytes.Buffer
    _, err = io.Copy(&buf, r)
    if err != nil {
    t.Fatalf("Failed to read captured output: %v", err)
    }

    output := buf.String()
    if !strings.Contains(output, "python boilerplate content") {
    t.Errorf("Output missing expected boilerplate content: %v", output)
    }
    if !strings.Contains(output, "Generated by gibo") {
    t.Errorf("Output missing expected header: %v", output)
    }
}

